"""One-off: port the dep-lab Debian results (oldlinux/fixes-v3.json, ol.py's two boxes, the two v3 map runs) into
the wend repo format, then prove the port is lossless: every ported fix must compile back to exactly the commands
ol.py ran, and pass ol.py's own VOCAB.

  python3 tools/port_oldlinux.py /mnt/project-files/dep-lab/oldlinux
"""
import importlib.util
import json
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import check  # noqa: E402
from tomlw import toml  # noqa: E402

SLUG = {"mysql-server-5.5 to mariadb-server on stretch": "mysql55-to-mariadb"}


# ---------- shell commands -> ops ----------

def when_of(s):
    neg = s.startswith("! ")
    s = s[2:] if neg else s
    if m := re.fullmatch(r"dpkg -s (\S+)", s):
        w = {"installed": m[1]}
    elif m := re.fullmatch(r"test -[ef] (\S+)", s):
        w = {"file": m[1]}
    else:
        raise ValueError(s)
    return {"not": w} if neg else w


def unprintf(body):
    return body.replace("\\n", "\n").replace("\\\\", "\\")


def op_of(c, adapter):
    if c == "apt-get -f install":
        return {"op": "repair"}
    if m := re.fullmatch(r"apt-get install (.+)", c):
        return {"op": "install", "packages": m[1].split()}
    if m := re.fullmatch(r"apt-get (purge|remove) (.+)", c):
        return {"op": "remove", "packages": m[2].split(), "purge": m[1] == "purge"}
    if m := re.fullmatch(r"dpkg --(purge|remove)((?: --force-[a-z-]+)*) (.+)", c):
        return {"op": "force-remove", "packages": m[3].split(), "purge": m[1] == "purge",
                "force": [x[len("--force-"):] for x in m[2].split()]}
    if m := re.fullmatch(r"printf '([^']*)' > (\S+)", c):
        content, path = unprintf(m[1]), m[2]
        for name, o in adapter["pm_options"].items():
            if o["path"] == path and o["content"] == content:
                return {"op": "pm-option", "option": name}
        return {"op": "write-file", "path": path, "content": content}
    if m := re.fullmatch(r"a2(en|dis)(site|mod|conf) (\S+)", c):
        return {"op": "apache.enable" if m[1] == "en" else "apache.disable", "kind": m[2], "name": m[3]}
    raise ValueError(c)


def found_by(f):
    src = f.get("from", "")
    if src.startswith("model"):
        return {"author": "claude-haiku-5-5 (grow mode, box b)", "curated_by": "claude (dep-lab)"}
    return {"author": "claude-haiku-5-5 (guided runs)", "curated_by": "claude (dep-lab)", "lab_note": src}


def port_fix(f, adapter):
    name = SLUG.get(f["name"], f["name"])
    doc = {"schema": "wend.fix/0", "family": "debian", "hop": f["hop"], "when": when_of(f["when"])}
    for ph in ("pre", "post"):
        if f.get(ph):
            doc[ph] = [op_of(c, adapter) for c in f[ph]]
    doc["restores"] = [c if c == "pkgdb" else f"box:{c}" for c in f.get("checks", [])]
    doc["adds"] = []
    meta = {"name": name, **found_by(f), "lab_name": f["name"], "source": "dep-lab oldlinux/fixes-v3.json"}
    if "when_before" in f:
        meta["superseded_when"] = f["when_before"]
    doc["meta"] = meta
    return doc


def claim(doc, boxes):
    """Which CI boxes this fix fires on. Every other box is a decoy it must stay off."""
    doc["meta"]["fires_on"] = sorted(boxes)
    return doc


def load_ol(lab, box):
    os.environ["OL_BOX"] = box
    spec = importlib.util.spec_from_file_location(f"ol_{box}", f"{lab}/ol.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


RUNS = (("a", "20261010-005241", "debian/etch-web"), ("b", "20261010-005243", "debian/etch-db"))


def main(lab):
    adapter = check.load_adapters()["debian"]
    ol = load_ol(lab, "a")
    lib = json.load(open(f"{lab}/fixes-v3.json"))["fixes"]
    fired = {}
    for box, stamp, bid in RUNS:
        for a in json.load(open(f"{lab}/results/map-{box}-{stamp}.json"))["applied"]:
            for n in a["library"]:
                fired.setdefault(n, []).append(bid)
    ids, problems = {}, []
    for f in lib:
        doc = claim(port_fix(f, adapter), fired.get(f["name"], []))
        # lossless: compiles back to exactly what ol.py ran, and passes ol.py's own vocabulary check
        back = check.compile_fix(doc, adapter)
        orig = {"when": f["when"], "pre": f.get("pre", []), "post": f.get("post", [])}
        if back != orig:
            problems.append(f"{f['name']}: round trip differs\n  {orig}\n  {back}")
        if e := ol.vocab_error({**back, "name": f["name"]}):
            problems.append(f"{f['name']}: ol.py VOCAB refuses the compiled form: {e}")
        p = f"{ROOT}/fixes/debian/{doc['hop']}/{doc['meta']['name']}.toml"
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(toml(doc, "# Ported from dep-lab. Generated by tools/port_oldlinux.py; edit freely, the id follows."))
        reread = check.tomllib.load(open(p, "rb"))
        if reread != doc or check.compile_fix(reread, adapter) != orig:
            problems.append(f"{f['name']}: the written TOML does not read back to the same fix")
        ids[f["name"]] = (check.content_id(doc), doc["meta"]["name"])

    # boxes: the two etch servers from ol.py, as CI fixtures
    boxes = {}
    for box, slug, summary in (("a", "etch-web", "etch web server: Apache 2.2 + mod_php5 vhost, postfix, ssh on 2222, cron"),
                               ("b", "etch-db", "etch database server: MySQL 5.0 with a real table, BIND master zone, Exim")):
        m = load_ol(lab, box)
        d = {"schema": "wend.box/0", "family": "debian", "release": "etch", "arch": "amd64",
             "summary": summary, "packages": m.PACKAGES.split(), "customize": m.CUSTOMIZE.strip() + "\n",
             "start_hook": m.EXPECT_CMD,
             "roles": {k: v for k, v in m.ROLES.items() if k not in ("pkgdb",)}}
        if m.PROFILE["debconf"]:
            d["debconf_selections"] = m.PROFILE["debconf"]
        p = f"{ROOT}/boxes/debian/{slug}/box.toml"
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(toml(d, "# CI fixture, ported from dep-lab oldlinux/ol.py (OL_BOX=" + box + ")."
                                "\n# Box files are trusted test code: humans review them, clients never run them."))
        boxes[box] = f"debian/{slug}"

    # the route: etch -> trixie with every fix pinned
    lad = adapter["ladder"]
    route = {"schema": "wend.route/0", "family": "debian", "arch": "amd64", "from": "etch", "to": "trixie",
             "hops": lad[1:], "finish": {"prune_obsolete": True},
             "fixes": [{"id": i, "name": n} for i, n in ids.values()],
             "meta": {"name": "etch-to-trixie", "summary": "Debian 4.0 (2007) to Debian 13, one release at a time"}}
    p = f"{ROOT}/routes/debian/etch-to-trixie.toml"
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write(toml(route, "# Every fix is pinned by content id: editing a fix changes its id, which edits this file,\n"
                                   "# which is how CI knows to replay this route."))
    rid = check.content_id(route)

    # runs: the two v3 no-model walks, as evidence
    for box, stamp, _ in RUNS:
        r = json.load(open(f"{lab}/results/map-{box}-{stamp}.json"))
        hops = []
        for a, s in zip(r["applied"], r["steps"]):
            fired = [ids[n][0] for n in a["library"]]
            hops.append({"to": a["hop"], "fired": fired, "fired_names": [ids[n][1] for n in a["library"]],
                         "ok": s["ok"], "seconds": s["seconds"]})
        run = {"schema": "wend.run/0", "route": rid, "box": boxes[box], "result": "pass" if not r["final"]["failed"] else "fail",
               "started": stamp, "wall_seconds": r["wall_seconds"],
               "runner": {"kind": "dep-lab chroot (Ubuntu 24.04 host, kernel 6.18)", "harness": "oldlinux/ol.py map --prune"},
               "hops": hops, "final": {"release": r["final"]["release"], "passed": r["final"]["passed"],
                                       "failed": r["final"]["failed"]},
               "obsolete_after": r.get("obsolete_after"), "model_calls": r["model_calls"],
               "evidence": f"dep-lab oldlinux/results/map-{box}-{stamp}.json"}
        p = f"{ROOT}/runs/debian/etch-to-trixie/{boxes[box].split('/')[1]}/{stamp}.json"
        os.makedirs(os.path.dirname(p), exist_ok=True)
        json.dump(run, open(p, "w"), indent=1)
        open(p, "a").write("\n")

    for x in problems:
        print("PORT PROBLEM", x)
    print(f"ported {len(ids)} fixes, 2 boxes, 1 route ({rid[:19]}), 2 runs; round trip "
          + ("ok" if not problems else "FAILED"))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
